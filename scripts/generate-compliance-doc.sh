#!/usr/bin/env bash
# generate-compliance-doc.sh — write the harness compliance mapping to a document.
#
# GOAP-276 Phase 2: "`compliance` output as compliance doc".
#
# `do-harness compliance` prints the OWASP Agentic Top 10 / NIST AI RMF /
# EU AI Act / SOC 2 mapping to stdout; `--output` is not honored by that
# subcommand, so the document is generated here and compared against the
# committed copy.
#
# Usage:
#   ./scripts/generate-compliance-doc.sh            # write the document
#   ./scripts/generate-compliance-doc.sh --check    # fail if the document is stale
#
# Exit: 0 = written or up to date, 1 = stale (with --check) or generation failed.

set -uo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.." || exit 1

TARGET="docs/compliance-mapping.md"
CHECK_MODE=0
if [[ "${1:-}" == "--check" ]]; then
  CHECK_MODE=1
fi

if ! command -v do-harness >/dev/null 2>&1; then
  echo "::warning::do-harness is not installed; cannot generate the compliance document"
  exit 0
fi

mkdir -p docs

GENERATED="$(do-harness compliance 2>/dev/null)"
if [ -z "${GENERATED}" ]; then
  echo "::error::do-harness compliance produced no output"
  exit 1
fi

# The harness's own table rows do not always carry as many cells as their
# table's header declares (some rows omit the trailing "Evidence" cell).
# markdownlint's MD056 rejects such a table, and the document is committed,
# so the rows are padded to the header's column count before they are
# written. An empty cell is the honest rendering of a missing column.
normalize_tables() {
  awk '
    BEGIN { FS = "|"; columns = 0 }
    /^\|/ {
      cells = NF - 2
      # A separator row (| --- | --- |) marks a new table and carries the
      # column count the following rows must match.
      if ($0 ~ /^[|][[:space:]]*-+[[:space:]]*([|][[:space:]]*-+[[:space:]]*)+[|]$/) {
        columns = cells
      }
      if (columns > 0 && cells < columns) {
        pad = columns - cells
        line = $0
        for (i = 0; i < pad; i++) line = line " |"
        print line
        next
      }
      if (columns > 0 && cells > columns) columns = cells
      print
      next
    }
    { print }
  '
}

# The generated mapping describes the harness itself, not this repository, so
# it is stored with a header that states what it is and is not.
{
  echo "# Compliance mapping (do-harness)"
  echo
  echo "<!-- Generated by scripts/generate-compliance-doc.sh — do not edit by hand. -->"
  echo "<!-- Regenerate: ./scripts/generate-compliance-doc.sh -->"
  echo
  echo 'The mapping below is the `do-harness` dev-loop control coverage. It'
  echo 'describes build-time and workflow-level verification controls only. It'
  echo 'is **not** a certification, an audit opinion, or a claim about this'
  echo "repository's production posture, and it makes no statement about the"
  echo 'deployed application.'
  echo
  printf '%s\n' "${GENERATED}" | normalize_tables
} > "${TARGET}.new.md"

# The repository is Prettier-clean, so the generated document must be too —
# otherwise the format gate and the drift check would disagree about the
# committed file. Prettier picks the parser from the file extension, so the
# formatting runs on the final path, not on the temporary one.
format_target() {
  local file="$1"
  [ -f "${file}" ] || return 0
  if command -v npx >/dev/null 2>&1; then
    npx --no-install prettier --write "${file}" >/dev/null 2>&1 \
      || npx prettier --write "${file}" >/dev/null 2>&1 \
      || true
  fi
}

if [ "${CHECK_MODE}" = "1" ]; then
  if [ ! -f "${TARGET}" ]; then
    echo "::error::${TARGET} is missing; run ./scripts/generate-compliance-doc.sh"
    rm -f "${TARGET}.new.md"
    exit 1
  fi
  # Compare against the formatted form, so the check agrees with what the
  # generator would write.
  cp "${TARGET}.new.md" "${TARGET}.check.md"
  format_target "${TARGET}.check.md"
  if ! diff -q "${TARGET}" "${TARGET}.check.md" >/dev/null 2>&1; then
    echo "::error::${TARGET} is stale; run ./scripts/generate-compliance-doc.sh and commit the result"
    diff "${TARGET}" "${TARGET}.check.md" | head -20 || true
    rm -f "${TARGET}.new.md" "${TARGET}.check.md"
    exit 1
  fi
  rm -f "${TARGET}.new.md" "${TARGET}.check.md"
  echo "${TARGET} is up to date."
  exit 0
fi

mv "${TARGET}.new.md" "${TARGET}"
format_target "${TARGET}"
echo "Wrote ${TARGET}"
