function bigHugeAttr(seed: number): string {
  let s = seed >>> 0;
  let out = '';
  for (let i = 0; i < 4096; i++) {
    s = (s * 1103515245 + 12345) >>> 0;
    const n = s % 62;
    out += String.fromCharCode(n < 10 ? 48 + n : n < 36 ? 97 + n - 10 : 65 + n - 36);
  }
  return out;
}

