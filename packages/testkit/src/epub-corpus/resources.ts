/**
 * Deterministic PRNG and programmatic embedded-resource synthesis for the
 * #1483 corpus (PNG/TTF/WAV). No vendored binaries: every byte is generated
 * from a seed at test time.
 */
import { deflateSync } from 'node:zlib';
import { crc32 } from './zip';

/**
 * Deterministic EPUB fixture generators for the #1483 corpus.
 *
 * Every archive is produced from in-repo templates at test time; nothing is
 * fetched from the network and no binary blob is vendored. Embedded resources
 * (PNG, TTF, WAV) are synthesized programmatically. All generators are pure
 * functions of their inputs — a fixed seed yields byte-identical output.
 */

// ---------------------------------------------------------------------------
// Deterministic PRNG (xorshift32)
// ---------------------------------------------------------------------------

export function prng(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    return (s >>> 0) / 0x100000000;
  };
}

// ---------------------------------------------------------------------------
// Embedded resource synthesis (programmatic, no vendored binaries)
// ---------------------------------------------------------------------------

/** Minimal 1×1 RGB PNG, generated byte-by-byte (zlib-wrapped deflate). */
export function generatePng(seed = 1): Uint8Array {
  const rng = prng(seed);
  const r = Math.floor(rng() * 256);
  const g = Math.floor(rng() * 256);
  const b = Math.floor(rng() * 256);
  const sig = Uint8Array.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

  const chunk = (type: string, data: Uint8Array): Uint8Array => {
    const typeBytes = new TextEncoder().encode(type);
    const out = Buffer.alloc(12 + data.length);
    out.writeUInt32BE(data.length, 0);
    out.set(typeBytes, 4);
    out.set(data, 8);
    out.writeUInt32BE(crc32(Buffer.concat([typeBytes, data])), 8 + data.length);
    return out;
  };

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(1, 0);
  ihdr.writeUInt32BE(1, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  const scanline = Uint8Array.from([0, r, g, b]);
  const idat = deflateSync(scanline, { level: 9 });
  return Uint8Array.from(
    Buffer.concat([sig, chunk('IHDR', ihdr), chunk('IDAT', idat), chunk('IEND', Buffer.alloc(0))]),
  );
}

/**
 * Minimal structurally-valid TrueType outline font (two empty glyphs).
 * Tables: head, hhea, maxp, cmap, glyf, loca, hmtx, name, post. SFNT table
 * checksums are computed; `head.checksumAdjustment` is left 0 (accepted by
 * platform font parsers). This covers the font *pipeline* (manifest item,
 * @font-face reference, resource shipping); it is not a full typeface.
 */
export function generateMinimalTtf(): Uint8Array {
  const u16 = (v: number) => {
    const b = Buffer.alloc(2);
    b.writeUInt16BE(v & 0xffff, 0);
    return b;
  };
  const u32 = (v: number) => {
    const b = Buffer.alloc(4);
    b.writeUInt32BE(v >>> 0, 0);
    return b;
  };

  const head = Buffer.concat([
    u32(0x00010000), // version
    u32(0x00010000), // fontRevision
    u32(0), // checkSumAdjustment (left 0)
    u32(0x5f0f3cf5), // magicNumber
    u16(0), // flags
    u16(1000), // unitsPerEm
    u32(0), // created
    u32(0), // modified
    u16(0), // xMin
    u16(0), // yMin
    u16(500), // xMax
    u16(500), // yMax
    u16(0), // macStyle
    u16(8), // lowestRecPPEM
    u16(2), // fontDirectionHint
    u16(0), // indexToLocFormat (short)
    u16(0), // glyphDataFormat
  ]);

  const hhea = Buffer.concat([
    u32(0x00010000),
    u16(800),
    u16(-200),
    u16(0), // lineGap
    u16(500), // advanceWidthMax
    u16(0), // minLeftSideBearing
    u16(0), // minRightSideBearing
    u16(500), // xMaxExtent
    u16(1), // caretSlopeRise
    u16(0), // caretSlopeRun
    u16(0), // caretOffset
    u16(0),
    u16(0),
    u16(0),
    u16(0), // reserved
    u16(0), // metricDataFormat
    u16(1), // numberOfHMetrics
  ]);

  const maxp = Buffer.concat([
    u32(0x00010000),
    u16(2), // numGlyphs
    u16(0),
    u16(0),
    u16(0),
    u16(0), // maxPoints/Contours/CompositePoints/CompositeContours
    u16(1), // maxZones
    u16(0),
    u16(0),
    u16(0),
    u16(0), // TwilightPoints/Storage/FunctionDefs/InstructionDefs
    u16(0),
    u16(0),
    u16(0),
    u16(0), // StackElements/SizeOfInstructions/ComponentElements/ComponentDepth
  ]);

  const cmapFormat4 = Buffer.concat([
    u16(4), // format
    u16(32), // length
    u16(0), // language
    u16(4), // segCountX2
    u16(4), // searchRange
    u16(1), // entrySelector
    u16(0), // rangeShift
    u16(0x0020),
    u16(0xffff), // endCode
    u16(0), // reservedPad
    u16(0x0020),
    u16(0xffff), // startCode
    u16(0xffe1),
    u16(0x0001), // idDelta
    u16(0),
    u16(0), // idRangeOffset
  ]);
  const cmap = Buffer.concat([
    u16(0), // version
    u16(1), // numTables
    u16(3), // platformID (Windows)
    u16(1), // encodingID (Unicode BMP)
    u32(12), // subtable offset
    cmapFormat4,
  ]);

  const glyf = Buffer.alloc(0);
  const loca = Buffer.from([0x00, 0x00, 0x00, 0x00, 0x00, 0x00]);
  const hmtx = Buffer.concat([u16(500), u16(0)]);

  const nameString = new TextEncoder().encode('Corpus Sans');
  const name = Buffer.concat([
    u16(0), // format
    u16(1), // count
    u16(6), // stringOffset
    u16(3), // platformID
    u16(1), // encodingID
    u16(0x0409), // languageID (en-US)
    u16(1), // nameID (family)
    u16(nameString.length),
    u16(0), // string offset
    nameString,
  ]);

  const post = Buffer.concat([
    u32(0x00030000),
    u32(0), // italicAngle
    u16(0), // underlinePosition
    u16(0), // underlineThickness
    u32(0), // isFixedPitch
    u32(0),
    u32(0),
    u32(0),
    u32(0), // memory minimums/maximums
  ]);

  const tables: Array<{ tag: string; data: Uint8Array }> = [
    { tag: 'head', data: head },
    { tag: 'hhea', data: hhea },
    { tag: 'maxp', data: maxp },
    { tag: 'cmap', data: cmap },
    { tag: 'glyf', data: glyf },
    { tag: 'loca', data: loca },
    { tag: 'hmtx', data: hmtx },
    { tag: 'name', data: name },
    { tag: 'post', data: post },
  ];

  const tableChecksum = (data: Uint8Array): number => {
    let sum = 0;
    for (let i = 0; i < data.length; i += 4) {
      const word = Buffer.from(data.subarray(i, Math.min(i + 4, data.length)));
      const padded = Buffer.alloc(4);
      padded.set(word);
      sum = (sum + padded.readUInt32BE(0)) >>> 0;
    }
    return sum;
  };

  const numTables = tables.length;
  const entrySize = 16;
  const dirSize = 12 + numTables * entrySize;
  let offset = dirSize;
  const dir = Buffer.alloc(dirSize);
  dir.writeUInt32BE(0x00010000, 0);
  dir.writeUInt16BE(numTables, 4);
  const maxPower = Math.floor(Math.log2(numTables));
  dir.writeUInt16BE(2 ** maxPower * 16, 6); // searchRange
  dir.writeUInt16BE(maxPower, 8); // entrySelector
  dir.writeUInt16BE(numTables * 16 - 2 ** maxPower * 16, 10); // rangeShift

  const parts: Uint8Array[] = [dir];
  tables.forEach((t, i) => {
    dir.writeUInt32BE(
      (t.tag.charCodeAt(0) << 24) |
        (t.tag.charCodeAt(1) << 16) |
        (t.tag.charCodeAt(2) << 8) |
        t.tag.charCodeAt(3),
      12 + i * entrySize,
    );
    dir.writeUInt32BE(tableChecksum(t.data), 12 + i * entrySize + 4);
    dir.writeUInt32BE(offset, 12 + i * entrySize + 8);
    dir.writeUInt32BE(t.data.length, 12 + i * entrySize + 12);
    parts.push(t.data);
    offset += t.data.length;
  });

  return Uint8Array.from(Buffer.concat(parts));
}

/** Minimal PCM WAV (mono, 16-bit, 8 kHz) with a deterministic 220 Hz tone. */
export function generateWav(samples = 2000): Uint8Array {
  const dataSize = samples * 2;
  const buf = Buffer.alloc(44 + dataSize);
  buf.write('RIFF', 0, 'ascii');
  buf.writeUInt32LE(36 + dataSize, 4);
  buf.write('WAVE', 8, 'ascii');
  buf.write('fmt ', 12, 'ascii');
  buf.writeUInt32LE(16, 16);
  buf.writeUInt16LE(1, 20); // PCM
  buf.writeUInt16LE(1, 22); // mono
  buf.writeUInt32LE(8000, 24);
  buf.writeUInt32LE(16000, 28); // byte rate
  buf.writeUInt16LE(2, 32); // block align
  buf.writeUInt16LE(16, 34); // bits per sample
  buf.write('data', 36, 'ascii');
  buf.writeUInt32LE(dataSize, 40);
  for (let i = 0; i < samples; i++) {
    const v = Math.round(Math.sin((2 * Math.PI * 220 * i) / 8000) * 8000);
    buf.writeInt16LE(v, 44 + i * 2);
  }
  return Uint8Array.from(buf);
}

